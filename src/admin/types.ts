export type EmployeeStatus = "active" | "inactive";
export type EmploymentType = "full-time" | "part-time" | "contract" | "intern";
export type WorkMode = "onsite" | "remote" | "hybrid";
/** Internal people are on monthly payroll; outsource people are paid per
 *  project through the ledger's Outsource category. */
export type StaffType = "internal" | "outsource";

export interface EmergencyContact {
  name: string;
  relationship: string;
  phone: string;
}

export interface Employee {
  id: string;
  /** Human-facing staff number: SL-2026-014. Assigned automatically. */
  employeeId: string;

  /**
   * Unguessable verification token, generated by the database.
   * The QR on an ID card carries THIS — never `employeeId`, which is sequential
   * and would let anyone enumerate the whole roster by counting upward.
   */
  verifyToken: string;

  fullName: string;
  role: string;
  department: string;
  manager: string;

  email: string;
  phone: string;
  cnic: string;
  dateOfBirth: string;
  address: string;
  /** Standard on Pakistani HR records and CNIC-verified documents. */
  fatherName: string;
  bloodGroup: string;
  /** National Tax Number — for employees who are FBR filers. */
  ntn: string;
  /** Where the salary goes. Printed on salary slips when set. */
  bankName: string;
  bankIban: string;

  status: EmployeeStatus;
  employmentType: EmploymentType;
  workMode: WorkMode;
  staffType: StaffType;

  joinedAt: string;
  /** Probation length in months. Drives the confirmation-due automation. */
  probationMonths: number;
  exitDate: string;

  salaryAmount: number;
  salaryCurrency: string;
  /** When the salary was last increased. Auto-stamped on raises. */
  lastRaiseAt: string;

  emergencyContact: EmergencyContact;

  /** Storage path (Supabase) or a data URL (local adapter). */
  photoPath: string;
  notes: string;

  /** Publishing. Flipping this puts the person on the public website. */
  showOnWebsite: boolean;
  publicBio: string;
}

